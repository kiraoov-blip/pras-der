"""충전사업자용 전기차 충전 실측부하 → lib/simulator/charging-operator-data.generated.ts

원자료: 제주_전기차_2025.xlsx (충전서비스 제공사업자용 고객의 시간대별 사용량)
  - 열: 고객번호, 검침일(YYYYMMDD), H01~H24 (kWh, H01 = 00~01시)
  - 고객번호 1개 = 충전소 사업장 1개

출력: 날짜별 24시간 사용량을 전체 사업장에 대해 합산한 값(kWh, 소수 1자리).
빈 칸은 0으로 본다. 연중 개업·폐업한 사업장은 해당 날짜에만 합산된다.

사용법:
    python3 scripts/extract-charging-operator-data.py <제주_전기차_2025.xlsx>
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import openpyxl

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "lib" / "simulator" / "charging-operator-data.generated.ts"


def main(source: str) -> None:
    workbook = openpyxl.load_workbook(source, read_only=True, data_only=True)
    sheet = workbook[workbook.sheetnames[0]]

    header = next(sheet.iter_rows(min_row=1, max_row=1, values_only=True))
    expected = ("고객번호", "검침일", *[f"H{h:02d}" for h in range(1, 25)])
    if tuple(header[:26]) != expected:
        raise SystemExit(f"예상한 열 구성이 아닙니다: {header[:26]}")

    daily: dict[str, list[float]] = {}
    sites: set[object] = set()
    rows = 0
    empty_cells = 0
    for row in sheet.iter_rows(min_row=2, values_only=True):
        site, date = row[0], row[1]
        if site is None:
            continue
        text = str(date)
        key = f"{text[:4]}-{text[4:6]}-{text[6:8]}"
        hourly = daily.setdefault(key, [0.0] * 24)
        for hour, value in enumerate(row[2:26]):
            if isinstance(value, (int, float)):
                hourly[hour] += value
            else:
                empty_cells += 1
        sites.add(site)
        rows += 1

    dates = sorted(daily)
    payload = {
        "source": Path(source).name,
        "year": int(dates[0][:4]),
        "siteCount": len(sites),
        "rowCount": rows,
        "emptyCellCount": empty_cells,
        "annualKwh": round(sum(sum(v) for v in daily.values()), 1),
        "dailyHourlyKwh": {d: [round(v, 1) for v in daily[d]] for d in dates},
    }

    body = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    OUTPUT.write_text(
        "// Generated by scripts/extract-charging-operator-data.py from 제주_전기차_2025.xlsx.\n"
        "// Do not hand-edit numeric values; update the extractor and regenerate instead.\n"
        "// 충전서비스 제공사업자용 전체 사업장의 날짜별 24시간 사용량 합계(kWh). 0번 = 00~01시.\n\n"
        "export interface ChargingOperatorData {\n"
        "  source: string; year: number; siteCount: number; rowCount: number;\n"
        "  emptyCellCount: number; annualKwh: number;\n"
        "  dailyHourlyKwh: Record<string, number[]>;\n"
        "}\n\n"
        f"export const CHARGING_OPERATOR_DATA: ChargingOperatorData = {body};\n",
        encoding="utf-8",
    )
    print(f"{OUTPUT.relative_to(ROOT)}: {len(dates)}일, 사업장 {len(sites):,}개, "
          f"연간 {payload['annualKwh']:,.1f} kWh, 빈 칸 {empty_cells:,}개")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
